
-- Tables creation for the project
CREATE TABLE departments (
    department_id   NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    department_name VARCHAR2(100) NOT NULL UNIQUE,
    location        VARCHAR2(100) NOT NULL
);


CREATE TABLE doctors (
    doctor_id       NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    first_name      VARCHAR2(50) NOT NULL,
    last_name       VARCHAR2(50) NOT NULL,
    specialty       VARCHAR2(100) NOT NULL,
    department_id   NUMBER NOT NULL,
    salary          NUMBER(10, 2) NOT NULL CHECK (salary > 0),
    hire_date       DATE DEFAULT SYSDATE NOT NULL,
    CONSTRAINT fk_doc_dept FOREIGN KEY (department_id) REFERENCES departments(department_id)
);


CREATE TABLE patients (
    patient_id      NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    first_name      VARCHAR2(50) NOT NULL,
    last_name       VARCHAR2(50) NOT NULL,
    dob             DATE NOT NULL,
    gender          VARCHAR2(10) CHECK (gender IN ('Male', 'Female', 'Other')),
    phone           VARCHAR2(20),
    address         VARCHAR2(200)
);


CREATE TABLE appointments (
    appointment_id   NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    patient_id       NUMBER NOT NULL,
    doctor_id        NUMBER NOT NULL,
    appointment_date DATE NOT NULL,
    status           VARCHAR2(20) DEFAULT 'Scheduled' CHECK (status IN ('Scheduled', 'Completed', 'Cancelled')),
    CONSTRAINT fk_appt_patient FOREIGN KEY (patient_id) REFERENCES patients(patient_id),
    CONSTRAINT fk_appt_doctor FOREIGN KEY (doctor_id) REFERENCES doctors(doctor_id)
);


CREATE TABLE allowances (
    allowance_id       NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    doctor_id          NUMBER NOT NULL,
    allowance_amount   NUMBER(10, 2) NOT NULL CHECK (allowance_amount >= 0),
    effective_date     DATE DEFAULT SYSDATE NOT NULL,
    CONSTRAINT fk_allow_doc FOREIGN KEY (doctor_id) REFERENCES doctors(doctor_id)
);


CREATE TABLE attendance (
    attendance_id   NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    doctor_id       NUMBER NOT NULL,
    attendance_date DATE NOT NULL,
    status          VARCHAR2(20) CHECK (status IN ('Present', 'Absent', 'Leave')),
    CONSTRAINT fk_att_doc FOREIGN KEY (doctor_id) REFERENCES doctors(doctor_id)
);

COMMIT;